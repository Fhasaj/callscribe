"""Prompt templates for the LLM pipeline."""
from __future__ import annotations


def build_summary_prompt(transcript: str, customer_name: str, call_date: str) -> str:
    return f"""You are an assistant that turns a raw call transcript into clean call \
notes for a business. The transcript is auto-generated by speech-to-text and may \
contain minor errors, filler words, or misheard words -- clean those up in your output.

Customer: {customer_name or "Unknown"}
Call date: {call_date}

Transcript:
\"\"\"
{transcript.strip() or "(no speech detected)"}
\"\"\"

Respond with ONLY a JSON object (no markdown, no commentary) with exactly these keys:
- "summary": an array of short bullet-point strings capturing the key points discussed
- "customer_email": a polite, professional follow-up email (plain text, ready to send) \
recapping the call for the customer, signed off generically (e.g. "Best regards")
- "tasks": an array of short, concrete action-item strings mentioned or implied in the \
call (e.g. "Send updated pricing sheet"). Use an empty array if there are none.

If the transcript has no real content, still return valid JSON with empty/minimal values.
"""


def build_yearly_narrative_prompt(year: int, summaries: list[str], stats: dict) -> str:
    joined = "\n".join(f"- {s}" for s in summaries[:200]) or "(no call summaries recorded)"
    return f"""You are an assistant writing a short year-in-review recap for a salesperson/\
account manager, based on their call notes from {year}.

Stats for {year}:
- Total calls: {stats.get('call_count', 0)}
- Total call time: {round(stats.get('total_seconds', 0) / 3600, 1)} hours
- Tasks completed: {stats.get('tasks_completed', 0)}
- Top customers by call count: {', '.join(c['name'] for c in stats.get('top_customers', [])[:5]) or 'n/a'}

Call summary bullets from throughout the year:
{joined}

Write a concise, upbeat but factual prose recap (3-5 short paragraphs) of what this \
person accomplished in {year}, grounded only in the information above -- do not invent \
specifics that aren't supported by it. Plain text, no markdown headers.
"""
