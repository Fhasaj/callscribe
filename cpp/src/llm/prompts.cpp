std::string build_summary_prompt(const std::string& transcript, const std::string& customer_name,
                                  const std::string& meeting_name, const std::string& participants,
                                  const std::string& call_date, const std::string& summary_instruction,
                                  const std::string& email_instruction, const std::string& tasks_instruction) {
    std::string summary_text = summary_instruction.empty() ? kDefaultSummaryPrompt : summary_instruction;
    std::string email_text = email_instruction.empty() ? kDefaultEmailPrompt : email_instruction;
    std::string tasks_text = tasks_instruction.empty() ? kDefaultTasksPrompt : tasks_instruction;

    std::ostringstream out;
    out << "You are an assistant that turns a raw call transcript into clean call notes for a "
           "business. The transcript is auto-generated by speech-to-text and may contain minor "
           "errors, filler words, or misheard words -- clean those up in your output. Each line is "
           "already prefixed with who said it (the user vs. the other participant(s)).\n\n";
    out << "Meeting: " << (meeting_name.empty() ? "(untitled)" : meeting_name) << "\n";
    out << "Customer: " << (customer_name.empty() ? "Unknown" : customer_name) << "\n";
    out << "Participants: " << (participants.empty() ? "(not specified)" : participants) << "\n";
    out << "Call date: " << call_date << "\n\n";
    out << "Transcript:\n\"\"\"\n" << (transcript.empty() ? "(no speech detected)" : transcript) << "\n\"\"\"\n\n";
    out << "Respond with ONLY a JSON object (no markdown, no commentary) with exactly these keys:\n";
    out << "- \"summary\": an array of strings. " << summary_text << "\n";
    out << "- \"customer_email\": a single plain-text string. " << email_text
        << " Separate paragraphs with a blank line, but write each paragraph as one continuous "
           "line -- do not hard-wrap it to a fixed column width.\n";
    out << "- \"tasks\": an array of short strings. " << tasks_text
        << " Use an empty array if there are none.\n\n";
    out << "If the transcript has no real content, still return valid JSON with empty/minimal values.\n";
    return out.str();
}

std::string build_transcript_chunk_prompt(const std::string& chunk, int index, int total) {
    std::ostringstream out;
    out << "This is part " << index << " of " << total
        << " of a long call transcript, auto-generated by speech-to-text. Each line is prefixed "
           "with who said it.\n\n";
    out << "Transcript part:\n\"\"\"\n" << chunk << "\n\"\"\"\n\n";
    out << "List the substantive points from THIS PART ONLY as short plain-text bullet lines "
           "starting with \"- \": what was discussed, decisions made, numbers/dates/names "
           "mentioned, and any action items or commitments. Clean up speech-to-text errors and "
           "drop filler. Do not add a preamble, a conclusion, or anything not present in this "
           "part.\n";
    return out.str();
}

std::string build_yearly_narrative_prompt(int year, const std::vector<std::string>& summaries, int call_count,
                                           long long total_seconds, int tasks_completed,
                                           const std::vector<std::pair<std::string, int>>& top_customers) {
    std::ostringstream out;
    out << "You are an assistant writing a short year-in-review recap for a salesperson/account "
           "manager, based on their call notes from "
        << year << ".\n\n";
    out << "Stats for " << year << ":\n";
    out << "- Total calls: " << call_count << "\n";
    out << "- Total call time: " << (total_seconds / 3600.0) << " hours\n";
    out << "- Tasks completed: " << tasks_completed << "\n";
    out << "- Top customers by call count: ";
    if (top_customers.empty()) {
        out << "n/a";
    } else {
        for (size_t i = 0; i < top_customers.size() && i < 5; ++i) {
            if (i) out << ", ";
            out << top_customers[i].first;
        }
    }
    out << "\n\nCall summary bullets from throughout the year:\n";
    if (summaries.empty()) {
        out << "(no call summaries recorded)\n";
    } else {
        size_t limit = summaries.size() < 200 ? summaries.size() : 200;
        for (size_t i = 0; i < limit; ++i) out << "- " << summaries[i] << "\n";
    }
    out << "\nWrite a concise, upbeat but factual prose recap (3-5 short paragraphs) of what this "
           "person accomplished in "
        << year
        << ", grounded only in the information above -- do not invent specifics that aren't "
           "supported by it. Plain text, no markdown headers.\n";
    return out.str();
}

std::string build_review_report_prompt(int year, const std::string& cycle_label,
                                        const std::vector<std::string>& questions,
                                        const std::vector<std::string>& summaries, int call_count,
                                        long long total_seconds, int tasks_completed,
                                        const std::vector<std::pair<std::string, int>>& top_customers) {
    std::ostringstream out;
    out << "You are helping a salesperson/account manager draft their " << cycle_label
        << " performance review self-assessment, using their own call notes from " << year
        << " as the evidence base.\n\n";
    out << "Activity for " << year << ":\n";
    out << "- Total calls: " << call_count << "\n";
    out << "- Total call time: " << (total_seconds / 3600.0) << " hours\n";
    out << "- Tasks completed: " << tasks_completed << "\n";
    out << "- Top customers by call count: ";
    if (top_customers.empty()) {
        out << "n/a";
    } else {
        for (size_t i = 0; i < top_customers.size() && i < 5; ++i) {
            if (i) out << ", ";
            out << top_customers[i].first;
        }
    }
    out << "\n\nCall summary bullets from throughout the year:\n";
    if (summaries.empty()) {
        out << "(no call summaries recorded)\n";
    } else {
        size_t limit = summaries.size() < 200 ? summaries.size() : 200;
        for (size_t i = 0; i < limit; ++i) out << "- " << summaries[i] << "\n";
    }

    out << "\nAnswer each of the following review questions, in order:\n";
    for (size_t i = 0; i < questions.size(); ++i) out << (i + 1) << ". " << questions[i] << "\n";

    out << "\nWrite the answers in the first person, as the person being reviewed. For each "
           "question, repeat the question as a plain-text heading line, then give 2-4 short "
           "paragraphs or bullets answering it. Ground every claim in the activity and call notes "
           "above -- cite concrete customers, deals, or action items where you can, and do not "
           "invent specifics that aren't supported. If the notes don't support an answer to a "
           "question, say plainly what evidence is missing rather than making something up. Plain "
           "text, no markdown headers.\n";
    return out.str();
}

std::string build_proofread_prompt(const std::string& email_text) {
    std::ostringstream out;
    out << "You are a professional editor proofreading a business email before it gets sent to a "
           "customer.\n\n";
    out << "Original email:\n\"\"\"\n" << email_text << "\n\"\"\"\n\n";
    out << "Rewrite it correcting grammar, spelling, punctuation, and awkward phrasing, and tighten "
           "unclear sentences -- but preserve the original meaning, intent, tone, and all factual "
           "details (names, dates, numbers, commitments). Do not add new content or remove "
           "substantive points. Respond with ONLY the corrected email text, no commentary, no "
           "markdown, no explanation of what changed.\n";
    return out.str();
}

std::string build_chat_prompt(const std::vector<ChatTurn>& history, const std::string& message,
                               const std::string& user_name) {
    std::ostringstream head;
    head << "You are CallScribe's assistant, helping"
         << (user_name.empty() ? "" : " " + user_name)
         << " -- someone who spends the day on customer calls -- with whatever they ask: drafting "
            "and rewording messages, thinking through a customer situation, summarizing, or just "
            "answering a question.\n\n";
    head << "Be direct and concise. Give the answer first and skip the preamble. Reply in plain "
            "text with no markdown formatting, since the reply is shown in a terminal. If you are "
            "unsure of a fact, say so rather than inventing it.\n\n";

    std::ostringstream tail;
    tail << "User: " << message << "\n";
    tail << "Assistant:";

    const std::string head_text = head.str();
    const std::string tail_text = tail.str();

    // Render the history newest-first into a stack of lines, stopping once the
    // whole prompt would outgrow the largest context window we ask for -- an
    // open-ended chat otherwise grows without bound.
    const long budget = max_prompt_chars() - static_cast<long>(head_text.size() + tail_text.size()) - 64;
    std::vector<std::string> lines;
    long used = 0;
    for (auto it = history.rbegin(); it != history.rend(); ++it) {
        std::string line = (it->is_user ? "User: " : "Assistant: ") + it->text + "\n";
        if (budget > 0 && used + static_cast<long>(line.size()) > budget) break;
        used += static_cast<long>(line.size());
        lines.push_back(std::move(line));
    }

    std::ostringstream out;
    out << head_text;
    if (!lines.empty()) {
        out << "Conversation so far:\n";
        for (auto it = lines.rbegin(); it != lines.rend(); ++it) out << *it;
        out << "\n";
    }
    out << tail_text;
    return out.str();
}

